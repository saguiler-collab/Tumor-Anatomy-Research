def J(name: str) -> dict:
    p = config.RESULTS_DIR / name
    if not p.exists():
        return {}
    try:
        return json.loads(p.read_text())
    except Exception:                                              # noqa: BLE001
        return {}


def pct(x, nd=1):
    return "—" if x is None else f"{x * 100:.{nd}f}%"


